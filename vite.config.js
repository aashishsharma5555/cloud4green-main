import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import basicSsl from "@vitejs/plugin-basic-ssl";
import { fileURLToPath, URL } from "node:url";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import {
  COMING_SOON,
  PAGES,
  absolute,
  headTags,
} from "./src/config/seo.js";

/**
 * seoPages — gives every route its own HTML, and the site its crawl files.
 *
 * This is a single-page app: without this, every URL is served the same
 * index.html, so every page has the same title, none has a description, and
 * a link shared on LinkedIn or Slack previews as "cloud4green" whatever page
 * it points at. Link-preview bots don't run JavaScript, so fixing the title
 * at runtime alone doesn't reach them.
 *
 * After the bundle is written, the one index.html becomes one file per page,
 * each with its own <head> (from src/config/seo.js) and the same app below it:
 *
 *   dist/index.html                    /
 *   dist/contact.html                  /contact
 *   dist/products/e-learning.html      /products/e-learning   … and so on
 *   dist/coming-soon.html              linked-but-unbuilt pages (noindex, 200)
 *   dist/404.html                      everything else (noindex, real 404)
 *   dist/sitemap.xml, robots.txt, _redirects (Netlify), .htaccess (Apache)
 *
 * _redirects is generated rather than kept in /public so it can't drift from
 * the route list: every page is rewritten to its own file, and the last rule
 * answers an unknown URL with a genuine 404 status instead of the 200 a bare
 * SPA fallback gives — which Google reports as a "soft 404" and which let any
 * mistyped URL be indexed as a copy of the homepage.
 */
function seoPages() {
  let outDir = "dist";
  const inject = (html, path) => html.replace("<!--seo-->", headTags(path));

  return {
    name: "c4g-seo-pages",
    configResolved(config) {
      outDir = config.build.outDir;
    },
    transformIndexHtml(html, ctx) {
      // Dev: fill the head for the page being requested. Build: leave the
      // marker, so closeBundle can write a different head into each copy.
      return ctx.server ? inject(html, ctx.originalUrl ?? "/") : html;
    },
    closeBundle() {
      const template = readFileSync(join(outDir, "index.html"), "utf8");
      if (!template.includes("<!--seo-->")) return; // not a client build
      const write = (file, body) => {
        mkdirSync(dirname(join(outDir, file)), { recursive: true });
        writeFileSync(join(outDir, file), body);
      };

      const pages = Object.keys(PAGES);
      const fileFor = (path) => (path === "/" ? "index.html" : `${path.slice(1)}.html`);

      for (const path of pages) write(fileFor(path), inject(template, path));
      write("coming-soon.html", inject(template, COMING_SOON[0]));
      write("404.html", inject(template, "/__not-found__"));

      const today = new Date().toISOString().slice(0, 10);
      write(
        "sitemap.xml",
        `<?xml version="1.0" encoding="UTF-8"?>\n` +
          `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
          pages
            .map(
              (path) =>
                `  <url><loc>${absolute(path)}</loc><lastmod>${today}</lastmod>` +
                `<priority>${PAGES[path].priority.toFixed(1)}</priority></url>`,
            )
            .join("\n") +
          `\n</urlset>\n`,
      );

      write(
        "robots.txt",
        `User-agent: *\nAllow: /\n\nSitemap: ${absolute("/sitemap.xml")}\n`,
      );

      // First match wins, so pages come before the coming-soon globs (one of
      // which sits under /services/automation) and the 404 catch-all is last.
      // Real files — the JS, CSS, PDF — are served before any of these apply.
      write(
        "_redirects",
        [
          "# Generated by the seoPages plugin in vite.config.js - edit",
          "# src/config/seo.js, not this file.",
          ...pages
            .filter((p) => p !== "/")
            .map((p) => `${p}  /${fileFor(p)}  200`),
          ...COMING_SOON.map((p) => `${p}  /coming-soon.html  200`),
          "/*  /404.html  404",
          "",
        ].join("\n"),
      );

      // The same rules for Apache (cPanel hosting), which ignores _redirects.
      // Real files are served before any rule applies, as on Netlify.
      const re = (p) => p.slice(1).replace(/[.+?^${}()|[\]\\-]/g, "\\$&");
      const rule = (p, target) =>
        p.endsWith("/*")
          ? `RewriteRule ^${re(p.slice(0, -2))}/.+$ ${target} [L]`
          : `RewriteRule ^${re(p)}/?$ ${target} [L]`;
      write(
        ".htaccess",
        [
          "# Generated by the seoPages plugin in vite.config.js - edit",
          "# src/config/seo.js, not this file.",
          "DirectoryIndex index.html",
          "ErrorDocument 404 /404.html",
          "",
          "RewriteEngine On",
          "",
          "# HTTPS only: the Bookings embed on /contact refuses plain HTTP.",
          "RewriteCond %{HTTPS} off",
          "RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]",
          "",
          "RewriteCond %{REQUEST_FILENAME} -f",
          "RewriteRule ^ - [L]",
          "",
          ...pages
            .filter((p) => p !== "/")
            .map((p) => rule(p, `/${fileFor(p)}`)),
          ...COMING_SOON.map((p) => rule(p, "/coming-soon.html")),
          "",
          "# Hashed build assets never change, so cache them for a year.",
          "<IfModule mod_headers.c>",
          '  <FilesMatch "\\.[0-9A-Za-z_-]{8,}\\.(js|css|woff2?)$">',
          '    Header set Cache-Control "public, max-age=31536000, immutable"',
          "  </FilesMatch>",
          "</IfModule>",
          "",
        ].join("\n"),
      );
    },
  };
}

/**
 * The dev server runs over HTTPS with a self-signed certificate. Expect a
 * browser warning on first visit each session — click through it.
 *
 * It is not decoration. The Microsoft Bookings embed on /contact is served with
 * `Content-Security-Policy: frame-ancestors https:`, a scheme-source that
 * admits any HTTPS origin and refuses every HTTP one, http://localhost very
 * much included. On a plain HTTP dev server that calendar is blocked outright
 * while working perfectly in production — a failure that shows up only where
 * you develop and never where you deploy, which is the worst way round. Serving
 * dev over TLS costs one click and keeps local behaviour honest.
 *
 * This affects local development only. Netlify builds with `vite build` and
 * serves the output over its own certificate; the dev server never runs there.
 */
export default defineConfig({
  plugins: [
    react(),
    tailwindcss(),
    basicSsl(),
    seoPages(),
  ],
  resolve: {
    alias: {
      "@": fileURLToPath(new URL("./src", import.meta.url)),
    },
  },
});